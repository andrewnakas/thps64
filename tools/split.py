#!/usr/bin/env python3
"""Re-split main from scratch: find_funcs seeds -> fresh asm/ (splat never deletes files of functions that no longer
exist, and build.py links every .s it finds) -> config/functions.csv.

  python tools/split.py
"""
import os
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


# splat, with one change to spimdisasm's function discovery: only `jal` makes a function start. spimdisasm also
# takes the target of every branch-and-link (bal, bltzal, bgezal, bltzall, bgezall); GCC never emits those, and the
# only three in main's .text are filler words between object files, so their targets cut real functions in two
# (`bgezall $t0` at 0x80026648 split func_80026650 at 0x800266CC, `bltzal $t8` at 0x8002EC7C split func_80046964
# at 0x8004698C).
SPLAT = """import sys
from spimdisasm.mips.sections.MipsSectionText import SectionText
def _findCalls(self, instrsList):
    for instr in instrsList:
        if instr.doesLink() and instr.isJumpWithAddress():
            self.addFunction(instr.getBranchVramGeneric(), isAutogenerated=True)
SectionText._findCalls = _findCalls
from splat.__main__ import splat_main
sys.argv[0] = 'splat'
splat_main()
"""


def run(*cmd, quiet=False):
    print('+', ' '.join('<splat>' if c == SPLAT else c for c in cmd), flush=True)
    subprocess.run(cmd, cwd=ROOT, check=True, stdout=subprocess.DEVNULL if quiet else None)


if __name__ == '__main__':
    run(sys.executable, 'tools/find_funcs.py')
    shutil.rmtree(os.path.join(ROOT, 'asm'), ignore_errors=True)   # generated (gitignored); boot lives in asm_boot/
    # splat writes src/game.c once and never rewrites it; a stale one silently changes the function set
    game_c = os.path.join(ROOT, 'src', 'game.c')
    if os.path.exists(game_c):
        os.remove(game_c)
    run(sys.executable, '-c', SPLAT, 'split', 'config/main.yaml', quiet=True)
    with open(os.path.join(ROOT, 'config', 'functions.csv'), 'w') as f:
        subprocess.run([sys.executable, 'tools/functable.py'], cwd=ROOT, check=True, stdout=f)
    print('config/functions.csv rewritten')
