#!/usr/bin/env python3
"""Seed splat with function starts it cannot see on its own (data words embedded in .text hide them).

  python tools/find_funcs.py   -> rewrites the generated block of config/symbol_addrs.txt
Starts = every jal target in main's text, every prologue soon after a return, plus every word in main's rodata/data that points into text
at an `addiu sp, sp, -N` prologue (function pointers: state tables, callbacks).
"""
import os
import re
import struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VRAM = 0x80016AC0
TEXT = (0xB900, 0xAA360)          # main.bin offsets (see config/main.yaml)
MARK = '// --- generated by tools/find_funcs.py ---'


def main():
    d = open(os.path.join(ROOT, 'work', 'main.bin'), 'rb').read()
    lo, hi = VRAM + TEXT[0], VRAM + TEXT[1]
    words = struct.unpack(f'>{len(d) // 4}I', d)
    jal, ptr = set(), set()
    for i, w in enumerate(words):
        off = 4 * i
        if TEXT[0] <= off < TEXT[1]:
            if w >> 26 == 3:
                t = 0x80000000 | ((w & 0x3FFFFFF) << 2)
                if lo <= t < hi:
                    jal.add(t)
        elif lo <= w < hi and w % 4 == 0:
            if words[(w - VRAM) // 4] >> 16 == 0x27BD and words[(w - VRAM) // 4] & 0x8000:
                ptr.add(w)
    # a prologue shortly after a return starts a function (constant pools sit between functions)
    after = set()
    for i in range(TEXT[0] // 4, TEXT[1] // 4 - 2):
        if words[i] == 0x03E00008:
            for j in range(i + 2, min(i + 2 + 16, TEXT[1] // 4)):
                if words[j] >> 16 == 0x27BD and words[j] & 0x8000:
                    after.add(VRAM + 4 * j)
                    break
                if words[j] == 0x03E00008:
                    break
    jal |= after
    p = os.path.join(ROOT, 'config', 'symbol_addrs.txt')
    keep = open(p).read().split(MARK)[0].rstrip('\n')
    hand = {int(m.group(1), 16) for m in re.finditer(r'=\s*(0x[0-9A-Fa-f]+)', keep)}
    lines = [keep, MARK]
    for a in sorted((jal | ptr) - hand):
        lines.append(f'func_{a:08X} = 0x{a:08X}; // type:func')
    open(p, 'w').write('\n'.join(lines) + '\n')
    print(f'{len(jal)} jal targets + prologues after returns ({len(after)}), {len(ptr)} data pointers to prologues, {len((jal | ptr) - hand)} written')


if __name__ == '__main__':
    main()
