#!/usr/bin/env python3
"""Seed splat with function starts it cannot see on its own (data words embedded in .text hide them).

  python tools/find_funcs.py   -> rewrites the generated block of config/symbol_addrs.txt
Starts = every jal target in main's text, every prologue soon after a return, plus every word in main's rodata/data that points into text
at an `addiu sp, sp, -N` prologue (function pointers: state tables, callbacks).
"""
import os
import re
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VRAM = 0x80016AC0
TEXT = (0xB900, 0xAA360)          # main.bin offsets (see config/main.yaml)
MARK = '// --- generated by tools/find_funcs.py ---'


def preamble_start(words, j, floor):
    """GCC may schedule global loads before the stack adjustment (lui v0,hi; lw v1,lo(v0); addiu sp,sp,-N), and
    varargs functions store a0-a3 into the caller's home slots first: walk back from the prologue at j over those
    stores, luis and loads/addius based on a register one of them set."""
    lui_regs, k = set(), j
    pending = []
    while k - 1 >= floor:
        w = words[k - 1]
        op, rs, rt = w >> 26, (w >> 21) & 31, (w >> 16) & 31
        if op == 15 and rs == 0:                                   # lui rt, hi
            lui_regs.add(rt)
            k -= 1
            continue
        if op == 0x2B and rs == 29 and 4 <= rt <= 7 and w & 0xFFFF == 4 * (rt - 4):   # varargs: sw aN, home slot(sp)
            k -= 1
            continue
        if op in (0x23, 0x21, 0x25, 0x20, 0x24, 9) and rs != 29:     # lw/lh/lhu/lb/lbu/addiu off(rs)
            pending.append(rs)
            k -= 1
            continue
        break
    # every load/addiu kept must be based on a lui inside the preamble, else start at the prologue
    return k if all(r in lui_regs for r in pending) else j


TAIL_REACH = 0x2000   # a branch this far past its unit is real control flow, not a misread data word


def split_tails(starts, guessed, words, hi):
    """Guessed starts (a prologue after a return, a leaf after `jr $ra`) that are really the rest of the function
    before them: switch cases and shared exits after an early return, which only a jump table or a branch reaches.
    A branch or `j` from one unit to a label inside a later (or earlier) unit means the starts in between are not
    function entries; called functions and data pointers to prologues are always kept. -> the starts to drop."""
    import recomp_syms
    drop, changed = set(), True
    while changed:
        changed = False
        live = [a for a in starts if a not in drop]
        for k, a in enumerate(live):
            b = live[k + 1] if k + 1 < len(live) else hi
            for p in range(a, b, 4):
                w = words[(p - VRAM) // 4]
                t = recomp_syms._branch_target(w, 0)
                t = p + 4 * t if t is not None else ((p & 0xF0000000) | ((w & 0x3FFFFFF) << 2) if w >> 26 == 2 else None)
                if t is None or a <= t < b or abs(t - p) > TAIL_REACH or (t in live and t not in guessed):
                    continue   # inside the unit, too far to trust, or a tail call to a real start
                between = [s for s in live if (b <= s <= t if t >= b else t < s <= a)]
                if between and all(s in guessed for s in between):
                    drop |= set(between)
                    changed = True
            if changed:
                break
    return drop


def reached_end(words, a, b, entries):
    """Index (in words from a) just past the last instruction that control flow reaches from the unit's start or
    from a data pointer into it (jump-table cases, callbacks): branches, `j` inside the unit, delay slots; a
    return, `j` or unconditional `b` ends a path. Words past it are never executed."""
    import recomp_syms
    n, seen, work = (b - a) // 4, set(), [0] + [(p - a) // 4 for p in entries if a < p < b]
    while work:
        i = work.pop()
        while 0 <= i < n and i not in seen:
            seen.add(i)
            w = words[(a - VRAM) // 4 + i]
            t = recomp_syms._branch_target(w, i)
            stop = False
            if t is not None:
                work.append(t)
                stop = w >> 16 in (0x1000, 0x0401)                  # b (beq $0,$0 / bgez $0)
            elif w >> 26 == 2:                                      # j: a label in here, else a tail call
                tj = ((a + 4 * i) & 0xF0000000) | ((w & 0x3FFFFFF) << 2)
                if a <= tj < b:
                    work.append((tj - a) // 4)
                stop = True
            elif w >> 26 == 0 and w & 0x3F == 8:                    # jr
                stop = True
            if t is not None or stop:
                seen.add(i + 1)                                     # delay slot
                if stop:
                    break
                i += 2
                continue
            i += 1
    return min(n, max(seen) + 1)


def fall_through(starts, guessed, words, hi, entries):
    """Guessed starts that the code before them runs into (no return, jump or `b` in its last two words, and control
    flow reaches its end): GCC scheduled an argument move ahead of the prologue, e.g. `mtc1 $a1,$f12` at 0x800A4350
    (called) before `addiu $sp,$sp,-0x50` at 0x800A4354 (found only by the prologue scan). -> starts to drop."""
    def ends_path(w):
        return w >> 26 == 2 or (w >> 26 == 0 and w & 0x3F == 8) or w >> 16 in (0x1000, 0x0401)
    starts, drop = sorted(starts), set()
    for k in range(1, len(starts)):
        p, a = starts[k - 1], starts[k]
        ws = words[(p - VRAM) // 4:(a - VRAM) // 4]
        if a in guessed and not any(ends_path(w) for w in ws[-2:]) and reached_end(words, p, a, entries) == len(ws):
            drop.add(a)
    return drop


def junk_word(w):
    """A word GCC 2.8.1 (-mgp32) never emits in the game's C code: invalid, a load/store based on $zero, a 64-bit
    integer op, $k0/$k1, COP0/COP2/COP3. Only used on the few words right before a 16-byte boundary."""
    import rabbitizer
    x = rabbitizer.Instruction(w)
    if not x.isValid():
        return True
    op, rs, rt = w >> 26, (w >> 21) & 31, (w >> 16) & 31
    if op in (0x10, 0x12, 0x13, 0x32, 0x33, 0x36, 0x37, 0x3A, 0x3B, 0x3E, 0x3F, 0x18, 0x19, 0x1A, 0x1B):
        return True                                                 # cop0/2/3, ld/sd, daddi(u), ldl/ldr
    if 0x20 <= op <= 0x2F and rs == 0:
        return True                                                 # load/store at an absolute address < 0x8000
    if op == 0 and (w & 0x3F) in (0x14, 0x16, 0x17, 0x2C, 0x2D, 0x2E, 0x2F, 0x38, 0x3A, 0x3B, 0x3C, 0x3E, 0x3F):
        return True                                                 # dsllv .. dsra32
    return op not in (0x11, 0x31, 0x35, 0x39, 0x3D) and bool({rs, rt, (w >> 11) & 31 if op == 0 else 0} & {26, 27})


def pad_tails(starts, words, hi, entries, guessed):
    """Filler between object files: 1-3 non-zero words after a function's code, up to the next 16-byte boundary
    where the next object file (function) starts (e.g. 0x8003A8FC, `swl $s4,0x3F6A($ra)` after the epilogue of
    func_8003A8B4). No C compiles to them, so they get their own asm-only unit `pad_XXXXXXXX`: build.py still links
    every .s, functable.py lists only func_ units, so they are not counted or offered as functions.
    "After the code" = past the last word control flow reaches (reached_end), so filler words that happen to decode
    as branches (0x8002C65C `blez`, 0x8002EC7C `bltzal`) no longer hide it. Two more shapes:
    - a guessed start (no caller, no pointer) 1-3 words before a 16-byte boundary whose words there can't be GCC
      code (junk_word: 0x8005E79C `lhu $t4,0x8F($zero)`): the function starts at the boundary, the words are filler;
    - filler and then, at the boundary, a small function nothing calls (0x80072F10 `jr $ra; move $v0,$zero`).
    -> (pad starts, starts to drop, starts to add)."""
    import recomp_syms
    starts = sorted(starts)
    drop, add = set(), set()
    for k, a in enumerate(starts):
        b = starts[k + 1] if k + 1 < len(starts) else hi
        s16 = (a + 15) & ~15
        if a in guessed and a % 16 and s16 < b and any(junk_word(words[(p - VRAM) // 4]) for p in range(a, s16, 4)) \
                and words[(s16 - VRAM) // 4 - 2] != 0x03E00008 \
                and recomp_syms.looks_like_code(words[(s16 - VRAM) // 4:(b - VRAM) // 4]):
            drop.add(a)
            add.add(s16)
    starts = sorted((set(starts) - drop) | add)
    pads = set()
    for k, a in enumerate(starts):
        b = starts[k + 1] if k + 1 < len(starts) else hi
        e = a + 4 * reached_end(words, a, b, entries)
        if e >= b:
            continue
        s16 = (e + 15) & ~15
        tail = words[(e - VRAM) // 4:(s16 - VRAM) // 4]
        if s16 == e or not any(tail) or 0x03E00008 in tail:
            continue
        if s16 == b:
            pads.add(e)
        elif s16 < b and any(junk_word(w) for w in tail) \
                and recomp_syms.looks_like_code(words[(s16 - VRAM) // 4:(b - VRAM) // 4]):
            pads.add(e)
            add.add(s16)
    return pads, drop, add


def main():
    d = open(os.path.join(ROOT, 'work', 'main.bin'), 'rb').read()
    lo, hi = VRAM + TEXT[0], VRAM + TEXT[1]
    words = struct.unpack(f'>{len(d) // 4}I', d)
    jal, ptr, prologue_ptr = set(), set(), set()
    for i, w in enumerate(words):
        off = 4 * i
        if TEXT[0] <= off < TEXT[1]:
            if w >> 26 == 3:
                t = 0x80000000 | ((w & 0x3FFFFFF) << 2)
                if lo <= t < hi:
                    jal.add(t)
        elif lo <= w < hi and w % 4 == 0:
            t = (w - VRAM) // 4
            if words[t] >> 16 == 0x27BD and words[t] & 0x8000:
                ptr.add(w)
                prologue_ptr.add(w)
            # GCC 2.x C++ vtables: {pointer, 0} pairs. Their entries may be leaf functions that start right after
            # another function's return or tail-call jump (jump tables, by contrast, are runs of bare words).
            elif (i + 1 < len(words) and words[i + 1] == 0) and (words[t - 2] == 0x03E00008 or words[t - 2] >> 26 == 2):
                ptr.add(w)
    # a prologue shortly after a return starts a function (constant pools sit between functions)
    after = set()
    for i in range(TEXT[0] // 4, TEXT[1] // 4 - 2):
        if words[i] == 0x03E00008:
            for j in range(i + 2, min(i + 2 + 16, TEXT[1] // 4)):
                if words[j] >> 16 == 0x27BD and words[j] & 0x8000:
                    after.add(VRAM + 4 * preamble_start(words, j, i + 2))
                    break
                if words[j] == 0x03E00008:
                    break
    # a prologue found only by scanning is not a start when real code runs into it: GCC schedules e.g. a div
    # expansion ahead of `addiu sp` (0x8009F1D0). Constant pools between functions are 1-3 words and rarely all
    # decode, so: a gap of 4+ valid instructions since the return means the earlier code continues here.
    import rabbitizer

    def falls_into(a):
        k = (a - VRAM) // 4
        r = k - 1
        while r > k - 20 and words[r] != 0x03E00008:
            r -= 1
        known = [q for q in range(r + 2, k) if VRAM + 4 * q in jal or VRAM + 4 * q in ptr]   # e.g. 0x8009F1D0
        gap = words[(known[0] if known else r + 2):k]
        return len(gap) >= 4 and any(gap) and all(rabbitizer.Instruction(g).isValid() for g in gap)
    after = {a for a in after if a in jal or not falls_into(a)}
    called = set(jal)   # real entry points: some code calls them
    jal |= after
    # leaf functions (no stack frame) after a return, reached only through pointers: split them off the way
    # recomp_syms does (a `jr $ra` no earlier branch jumps past, then code that ends in a return)
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import recomp_syms
    starts = sorted(a for a in jal | ptr if lo <= a < hi)
    funcs = [(a, b - a, f'func_{a:08X}') for a, b in zip(starts, starts[1:] + [hi])]
    jal |= {a for a, _, _ in recomp_syms.split_leaves(funcs, VRAM, d)} - set(starts)
    p = os.path.join(ROOT, 'config', 'symbol_addrs.txt')
    keep = open(p).read().split(MARK)[0].rstrip('\n')
    hand = {int(m.group(1), 16) for m in re.finditer(r'=\s*(0x[0-9A-Fa-f]+)', keep)}
    guessed = (jal | ptr) - called - prologue_ptr - hand
    tails = split_tails(sorted(a for a in jal | ptr | hand if lo <= a < hi), guessed, words, hi)
    jal -= tails
    ptr -= tails
    text_ptrs = {w for i, w in enumerate(words) if not TEXT[0] <= 4 * i < TEXT[1] and lo <= w < hi and w % 4 == 0}
    falls = fall_through({a for a in jal | ptr | hand if lo <= a < hi}, guessed - tails, words, hi, text_ptrs)
    jal -= falls
    pads, junk, leaves = pad_tails({a for a in jal | ptr | hand if lo <= a < hi}, words, hi, text_ptrs,
                                   guessed - tails)
    jal = (jal - junk) | leaves
    pads -= jal | ptr | hand
    lines = [keep, MARK]
    for a in sorted((jal | ptr) - hand):
        lines.append(f'func_{a:08X} = 0x{a:08X}; // type:func')
    for a in sorted(pads):
        lines.append(f'pad_{a:08X} = 0x{a:08X}; // type:func')
    open(p, 'w').write('\n'.join(lines) + '\n')
    print(f'{len(jal)} jal targets + prologues after returns ({len(after)}), {len(ptr)} data pointers to prologues, '
          f'{len(tails)} guessed starts merged back (branched over), {len(pads)} inter-file pads split off '
          f'({len(junk)} starts moved past filler, {len(leaves) - len(junk)} leaves after filler), '
          f'{len(falls)} guessed starts merged back (run into), '
          f'{len((jal | ptr) - hand)} written')


if __name__ == '__main__':
    main()
