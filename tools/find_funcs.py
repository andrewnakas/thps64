#!/usr/bin/env python3
"""Seed splat with function starts it cannot see on its own (data words embedded in .text hide them).

  python tools/find_funcs.py   -> rewrites the generated block of config/symbol_addrs.txt
Starts = every jal target in main's text, every prologue soon after a return, plus every word in main's rodata/data that points into text
at an `addiu sp, sp, -N` prologue (function pointers: state tables, callbacks).
"""
import os
import re
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VRAM = 0x80016AC0
TEXT = (0xB900, 0xAA360)          # main.bin offsets (see config/main.yaml)
MARK = '// --- generated by tools/find_funcs.py ---'


def preamble_start(words, j, floor):
    """GCC may schedule global loads before the stack adjustment (lui v0,hi; lw v1,lo(v0); addiu sp,sp,-N), and
    varargs functions store a0-a3 into the caller's home slots first: walk back from the prologue at j over those
    stores, luis and loads/addius based on a register one of them set."""
    lui_regs, k = set(), j
    pending = []
    while k - 1 >= floor:
        w = words[k - 1]
        op, rs, rt = w >> 26, (w >> 21) & 31, (w >> 16) & 31
        if op == 15 and rs == 0:                                   # lui rt, hi
            lui_regs.add(rt)
            k -= 1
            continue
        if op == 0x2B and rs == 29 and 4 <= rt <= 7 and w & 0xFFFF == 4 * (rt - 4):   # varargs: sw aN, home slot(sp)
            k -= 1
            continue
        if op in (0x23, 0x21, 0x25, 0x20, 0x24, 9) and rs != 29:     # lw/lh/lhu/lb/lbu/addiu off(rs)
            pending.append(rs)
            k -= 1
            continue
        break
    # every load/addiu kept must be based on a lui inside the preamble, else start at the prologue
    return k if all(r in lui_regs for r in pending) else j


TAIL_REACH = 0x2000   # a branch this far past its unit is real control flow, not a misread data word


def split_tails(starts, guessed, words, hi):
    """Guessed starts (a prologue after a return, a leaf after `jr $ra`) that are really the rest of the function
    before them: switch cases and shared exits after an early return, which only a jump table or a branch reaches.
    A branch or `j` from one unit to a label inside a later (or earlier) unit means the starts in between are not
    function entries; called functions and data pointers to prologues are always kept. -> the starts to drop."""
    import recomp_syms
    drop, changed = set(), True
    while changed:
        changed = False
        live = [a for a in starts if a not in drop]
        for k, a in enumerate(live):
            b = live[k + 1] if k + 1 < len(live) else hi
            for p in range(a, b, 4):
                w = words[(p - VRAM) // 4]
                t = recomp_syms._branch_target(w, 0)
                t = p + 4 * t if t is not None else ((p & 0xF0000000) | ((w & 0x3FFFFFF) << 2) if w >> 26 == 2 else None)
                if t is None or a <= t < b or abs(t - p) > TAIL_REACH or (t in live and t not in guessed):
                    continue   # inside the unit, too far to trust, or a tail call to a real start
                between = [s for s in live if (b <= s <= t if t >= b else t < s <= a)]
                if between and all(s in guessed for s in between):
                    drop |= set(between)
                    changed = True
            if changed:
                break
    return drop


def main():
    d = open(os.path.join(ROOT, 'work', 'main.bin'), 'rb').read()
    lo, hi = VRAM + TEXT[0], VRAM + TEXT[1]
    words = struct.unpack(f'>{len(d) // 4}I', d)
    jal, ptr, prologue_ptr = set(), set(), set()
    for i, w in enumerate(words):
        off = 4 * i
        if TEXT[0] <= off < TEXT[1]:
            if w >> 26 == 3:
                t = 0x80000000 | ((w & 0x3FFFFFF) << 2)
                if lo <= t < hi:
                    jal.add(t)
        elif lo <= w < hi and w % 4 == 0:
            t = (w - VRAM) // 4
            if words[t] >> 16 == 0x27BD and words[t] & 0x8000:
                ptr.add(w)
                prologue_ptr.add(w)
            # GCC 2.x C++ vtables: {pointer, 0} pairs. Their entries may be leaf functions that start right after
            # another function's return or tail-call jump (jump tables, by contrast, are runs of bare words).
            elif (i + 1 < len(words) and words[i + 1] == 0) and (words[t - 2] == 0x03E00008 or words[t - 2] >> 26 == 2):
                ptr.add(w)
    # a prologue shortly after a return starts a function (constant pools sit between functions)
    after = set()
    for i in range(TEXT[0] // 4, TEXT[1] // 4 - 2):
        if words[i] == 0x03E00008:
            for j in range(i + 2, min(i + 2 + 16, TEXT[1] // 4)):
                if words[j] >> 16 == 0x27BD and words[j] & 0x8000:
                    after.add(VRAM + 4 * preamble_start(words, j, i + 2))
                    break
                if words[j] == 0x03E00008:
                    break
    # a prologue found only by scanning is not a start when real code runs into it: GCC schedules e.g. a div
    # expansion ahead of `addiu sp` (0x8009F1D0). Constant pools between functions are 1-3 words and rarely all
    # decode, so: a gap of 4+ valid instructions since the return means the earlier code continues here.
    import rabbitizer

    def falls_into(a):
        k = (a - VRAM) // 4
        r = k - 1
        while r > k - 20 and words[r] != 0x03E00008:
            r -= 1
        known = [q for q in range(r + 2, k) if VRAM + 4 * q in jal or VRAM + 4 * q in ptr]   # e.g. 0x8009F1D0
        gap = words[(known[0] if known else r + 2):k]
        return len(gap) >= 4 and any(gap) and all(rabbitizer.Instruction(g).isValid() for g in gap)
    after = {a for a in after if a in jal or not falls_into(a)}
    called = set(jal)   # real entry points: some code calls them
    jal |= after
    # leaf functions (no stack frame) after a return, reached only through pointers: split them off the way
    # recomp_syms does (a `jr $ra` no earlier branch jumps past, then code that ends in a return)
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import recomp_syms
    starts = sorted(a for a in jal | ptr if lo <= a < hi)
    funcs = [(a, b - a, f'func_{a:08X}') for a, b in zip(starts, starts[1:] + [hi])]
    jal |= {a for a, _, _ in recomp_syms.split_leaves(funcs, VRAM, d)} - set(starts)
    p = os.path.join(ROOT, 'config', 'symbol_addrs.txt')
    keep = open(p).read().split(MARK)[0].rstrip('\n')
    hand = {int(m.group(1), 16) for m in re.finditer(r'=\s*(0x[0-9A-Fa-f]+)', keep)}
    guessed = (jal | ptr) - called - prologue_ptr - hand
    tails = split_tails(sorted(a for a in jal | ptr | hand if lo <= a < hi), guessed, words, hi)
    jal -= tails
    ptr -= tails
    lines = [keep, MARK]
    for a in sorted((jal | ptr) - hand):
        lines.append(f'func_{a:08X} = 0x{a:08X}; // type:func')
    open(p, 'w').write('\n'.join(lines) + '\n')
    print(f'{len(jal)} jal targets + prologues after returns ({len(after)}), {len(ptr)} data pointers to prologues, '
          f'{len(tails)} guessed starts merged back (branched over), {len((jal | ptr) - hand)} written')


if __name__ == '__main__':
    main()
